def get_states():
    """Returns a sorted list of all available state names."""
    return sorted(INDIA_PINCODES.keys())


def get_pincodes_for_state(state_name: str):
    """
    Returns a list of pincodes for the given state name.
    Case-insensitive matching.
    """
    state_name = state_name.strip()
    # Exact match first
    if state_name in INDIA_PINCODES:
        return [str(p) for p in INDIA_PINCODES[state_name]]
    # Case-insensitive match
    for key in INDIA_PINCODES:
        if key.lower() == state_name.lower():
            return [str(p) for p in INDIA_PINCODES[key]]
    return []
